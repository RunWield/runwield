import { test } from "node:test";
import { strictEqual, deepStrictEqual, rejects } from "node:assert/strict";
import { readFile, rm, writeFile } from "node:fs/promises";
import { join } from "node:path";
import { makeValidationProjectRoot } from "./validation-test-helpers.js";
import { withLocalPlanWorkflow } from "../../plan-store/index.ts";
import {
    assertPackageWorkflowInput,
    recoverGeneratedManualQaArtifact,
    saveGeneratedManualQaArtifact,
    selectedPackage,
} from "../../plan-store/workflows.ts";

test("generated checklist retains reviewed input and rejects later document edits", async () => {
    const root = await makeValidationProjectRoot("epic", { classification: "PROJECT", status: "draft" });
    await makeValidationProjectRoot(
        "child",
        { classification: "PLANNED_CHANGE", status: "reviewed", parentPlan: "epic" },
        "# Child",
        root,
    );
    await withLocalPlanWorkflow(root, "child", async () => {
        const before = await selectedPackage("child");
        const input = before.metadata.workflow!.attempt!.input;
        const parent = await selectedPackage("epic");
        const path = join(parent.path, "manual-qa.md");
        const text = "# Manual QA\n\n- [ ] Check delivered behavior\n";
        await saveGeneratedManualQaArtifact("child", "epic", null, text);
        deepStrictEqual((await selectedPackage("child")).metadata.workflow!.attempt!.input, input);
        await assertPackageWorkflowInput("child", input);
        strictEqual(await readFile(path, "utf8"), text);
        // A crash after recording the generated bytes but before replacing the document is replayable.
        await rm(path);
        await recoverGeneratedManualQaArtifact("child");
        strictEqual(await readFile(path, "utf8"), text);
        await writeFile(path, "# User changed this checklist\n");
        await rejects(() => recoverGeneratedManualQaArtifact("child"), /document changed/);
        await rejects(() => assertPackageWorkflowInput("child", input), /documents changed/);
    });
});
